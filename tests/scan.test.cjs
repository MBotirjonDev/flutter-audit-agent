'use strict';
/**
 * Zero-dependency tests:  node tests/scan.test.cjs   (or: npm test)
 *
 * Secret-shaped fixtures (API keys, bot tokens, private keys) are assembled at
 * runtime from fragments so that GitHub push protection and secret scanners
 * never see a real-looking credential in this repository.
 */
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SKILL = path.join(ROOT, 'skills', 'flutter-security-audit');
const { scan } = require(path.join(SKILL, 'scripts', 'scan.cjs'));
const RULES = require(path.join(SKILL, 'scripts', 'rules.cjs'));

let passed = 0;
let failed = 0;
function test(name, fn) {
  try { fn(); passed++; console.log(`  ok   ${name}`); }
  catch (e) { failed++; console.log(`  FAIL ${name}\n       ${e.message}`); }
}

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

// Build the vulnerable fixture in a temp dir and add generated secrets.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fsa-test-'));
const vulnDir = path.join(tmp, 'vuln_app');
copyDir(path.join(__dirname, 'fixtures', 'vuln_app'), vulnDir);
const fake = (n) => 'x'.repeat(n).replace(/x/g, (_, i) => 'FAKE0'[i % 5]);
const secrets = [
  '// generated by tests/scan.test.cjs — fake values only',
  `const mapsKey = '${'AI' + 'za'}${fake(35)}';`,
  `const botToken = '1234567890:${'A' + 'A'}${fake(33)}';`,
  `const stripeKey = '${'sk' + '_live_'}${fake(18)}';`,
  `const pem = '''${'-----BEGIN ' + 'PRIVATE KEY-----'}\nnot-a-real-key\n-----END PRIVATE KEY-----''';`,
].join('\n');
fs.writeFileSync(path.join(vulnDir, 'lib', 'secrets.dart'), secrets + '\n');
fs.writeFileSync(path.join(vulnDir, '.env'), 'API_BASE=https://api.example-shop.uz\n');
// Generated Firebase config must NOT trigger FSA-SEC-001.
fs.writeFileSync(path.join(vulnDir, 'lib', 'firebase_options.dart'), `const k = '${'AI' + 'za'}${fake(35)}';\n`);

console.log('\nflutter-security-audit tests\n');

const vuln = scan(vulnDir);
const hits = new Set(vuln.leads.map((l) => l.rule));

test('every rule fires on the vulnerable fixture', () => {
  const missing = RULES.map((r) => r.id).filter((id) => !hits.has(id));
  assert.deepStrictEqual(missing, [], `rules with no positive fixture: ${missing.join(', ')}`);
});

test('clean fixture produces zero leads', () => {
  const clean = scan(path.join(__dirname, 'fixtures', 'clean_app'));
  assert.strictEqual(clean.leads.length, 0, JSON.stringify(clean.leads.map((l) => `${l.rule} ${l.file}:${l.line}`)));
});

test('generated firebase_options.dart is excluded from FSA-SEC-001', () => {
  assert.ok(!vuln.leads.some((l) => l.rule === 'FSA-SEC-001' && l.file.endsWith('firebase_options.dart')));
});

test('MainActivity export is not flagged, other exported activities are', () => {
  const exported = vuln.leads.filter((l) => l.rule === 'FSA-AND-003');
  assert.strictEqual(exported.length, 1);
  assert.ok(exported[0].snippet.includes('PaymentResultActivity'));
});

test('snippets redact long secret values', () => {
  const key = vuln.leads.find((l) => l.rule === 'FSA-SEC-001');
  assert.ok(key && !key.snippet.includes(fake(35)), 'API key should be truncated in the snippet');
});

test('rule ids are unique and well-formed', () => {
  const ids = RULES.map((r) => r.id);
  assert.strictEqual(new Set(ids).size, ids.length, 'duplicate rule id');
  for (const r of RULES) {
    assert.match(r.id, /^FSA-[A-Z]{2,4}-\d{3}$/, r.id);
    for (const k of ['title', 'severity', 'files', 'pattern', 'masvs', 'guide', 'message', 'fix']) {
      assert.ok(r[k], `${r.id} missing ${k}`);
    }
    const guideFile = r.guide.split('#')[0];
    assert.ok(fs.existsSync(path.join(SKILL, 'checks', guideFile)), `${r.id}: checks/${guideFile} not found`);
  }
});

test('every rule guide anchor exists in its checks file', () => {
  const slug = (h) => h.toLowerCase().replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');
  for (const r of RULES) {
    const [file, anchor] = r.guide.split('#');
    const md = fs.readFileSync(path.join(SKILL, 'checks', file), 'utf8');
    const anchors = [...md.matchAll(/^#{2,4}\s+(.+)$/gm)].map((m) => slug(m[1]));
    assert.ok(anchors.includes(anchor), `${r.id}: #${anchor} not found in ${file}`);
  }
});

test('CLI --fail-on exits 1 on the vulnerable fixture and 0 on the clean one', () => {
  const cli = path.join(SKILL, 'scripts', 'scan.cjs');
  let code = 0;
  try { execFileSync('node', [cli, vulnDir, '--quiet', '--fail-on', 'high']); } catch (e) { code = e.status; }
  assert.strictEqual(code, 1);
  execFileSync('node', [cli, path.join(__dirname, 'fixtures', 'clean_app'), '--quiet', '--fail-on', 'info']);
});

test('CLI --out writes valid JSON', () => {
  const out = path.join(tmp, 'leads.json');
  execFileSync('node', [path.join(SKILL, 'scripts', 'scan.cjs'), vulnDir, '--quiet', '--out', out]);
  const parsed = JSON.parse(fs.readFileSync(out, 'utf8'));
  assert.ok(Array.isArray(parsed.leads) && parsed.leads.length > 0);
});

test('findings validator accepts the example and rejects a broken record', () => {
  const validator = path.join(SKILL, 'scripts', 'validate-findings.cjs');
  execFileSync('node', [validator, path.join(SKILL, 'templates', 'findings.example.json')]);
  const bad = path.join(tmp, 'bad.json');
  fs.writeFileSync(bad, JSON.stringify({ target: 'x', findings: [{ id: 'F-1', verdict: 'confirmed' }] }));
  let code = 0;
  try { execFileSync('node', [validator, bad], { stdio: 'pipe' }); } catch (e) { code = e.status; }
  assert.strictEqual(code, 1);
});

fs.rmSync(tmp, { recursive: true, force: true });
console.log(`\n${passed} passed, ${failed} failed\n`);
process.exit(failed ? 1 : 0);
